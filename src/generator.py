"""Markdown profile generator combining structured models and badges."""

from src.models import ProfileConfig
from src.badges import shield_badge, social_badge, skillicons_url


def generate_profile_markdown(cfg: ProfileConfig) -> str:
    """Compile ProfileConfig into a clean, concise, visually appealing GitHub profile README."""
    social_badges_html = " ".join(social_badge(s) for s in cfg.socials)
    skillicons_img = skillicons_url(cfg.skillicons)

    # Tech Stack categorized badges
    tech_stack_sections = []
    for cat_name, items in cfg.tech_categories.items():
        badges_str = "\n  ".join(shield_badge(item) for item in items)
        tech_stack_sections.append(
            f"#### **{cat_name}**\n<p align=\"left\">\n  {badges_str}\n</p>"
        )
    tech_stack_rendered = "\n\n".join(tech_stack_sections)

    # Featured projects section
    projects_rendered = []
    for p in cfg.featured_projects:
        tech_pills = " ".join(f"`{t}`" for t in p.tech_stack)
        bullets = "\n".join(f"- {h}" for h in p.highlights)
        projects_rendered.append(
            f"### ⚡ [{p.title}]({p.repo_url})\n"
            f"> **{p.subtitle}**  \n"
            f"> **Stack:** {tech_pills}\n\n"
            f"{bullets}"
        )
    projects_block = "\n\n".join(projects_rendered)

    # Honors & awards
    honors_rendered = "\n".join(f"- 🏆 **{h}**" for h in cfg.honors)

    markdown = f"""<!--
  Dynamically generated by Python profile engine (src/generator.py).
  Automated CI/CD via GitHub Actions.
-->

<div align="center">
  <img src="https://capsule-render.vercel.app/api?type=waving&color=gradient&customColorList=1,12,24,30&height=180&section=header&text={cfg.name.replace(' ', '%20')}&fontSize=42&fontAlignY=38&desc={cfg.headline.replace(' ', '%20')}&descFontSize=18&descAlignY=62&theme=dark" width="100%" alt="Header Banner" />
  
  <h1>Hi there, I'm {cfg.name} 👋</h1>
  <p><b>{cfg.headline}</b></p>
</div>

<p align="center">
  {social_badges_html}
</p>

---

### 📌 Quick Overview

{chr(10).join(f"- {b}" for b in cfg.bio_bullets)}
- 📍 **Location:** {cfg.location}
- 🎓 **Education:** {cfg.university} — {cfg.degree}

<details>
<summary><b>🎖️ Honors & Academic Recognition</b></summary>

{honors_rendered}

</details>

---

### 🛠️ Tech Stack & Tooling

<p align="center">
  <img src="{skillicons_img}" alt="Tech Stack Icons" />
</p>

{tech_stack_rendered}

---

### 🚀 Featured Engineering Projects

{projects_block}

---

### 📊 GitHub Activity & Insights

<div align="center">
  <a href="https://github.com/{cfg.username}">
    <img src="https://github-readme-stats.vercel.app/api?username={cfg.username}&show_icons=true&theme=radical&hide_border=true&count_private=true" alt="GitHub Stats" height="165" />
  </a>
  <a href="https://github.com/{cfg.username}">
    <img src="https://github-readme-stats.vercel.app/api/top-langs/?username={cfg.username}&layout=compact&theme=radical&hide_border=true" alt="Top Languages" height="165" />
  </a>
</div>

<p align="center">
  <img src="https://github-readme-streak-stats.herokuapp.com/?user={cfg.username}&theme=radical&hide_border=true" alt="Streak Stats" />
</p>

---

### 📬 Connect With Me

<p align="left">
  <a href="mailto:anh.nth1305@gmail.com">
    <img src="https://img.shields.io/badge/Email-anh.nth1305@gmail.com-D14836?style=for-the-badge&logo=gmail&logoColor=white" alt="Email" />
  </a>
  <a href="https://linkedin.com/in/hong-anh-23a103448">
    <img src="https://img.shields.io/badge/LinkedIn-Nguyen_Thi_Hong_Anh-0077B5?style=for-the-badge&logo=linkedin&logoColor=white" alt="LinkedIn" />
  </a>
  <a href="https://github.com/{cfg.username}">
    <img src="https://img.shields.io/badge/GitHub-@sweeti3--pie-181717?style=for-the-badge&logo=github&logoColor=white" alt="GitHub" />
  </a>
</p>

---

<p align="center">
  <i>"{cfg.quote}"</i>
</p>
"""
    return markdown
